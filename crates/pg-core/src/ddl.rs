//! `CREATE TABLE` text from catalog facts. Pure: the catalog code gathers the facts,
//! this module only formats them, so it can be unit-tested without a server.

use crate::catalog::{
    ColumnInfo, ConstraintInfo, Identity, IndexInfo, RelationKind, SequenceInfo, TableDetails,
    TriggerState,
};

/// Everything `build_ddl` needs besides the details themselves.
pub(crate) struct DdlNames<'a> {
    /// Quotes an identifier the way the server would (`quote_ident`).
    pub quote: &'a dyn Fn(&str) -> String,
}

fn literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

fn type_max(data_type: &str) -> &'static str {
    match data_type {
        "smallint" => "32767",
        "integer" => "2147483647",
        _ => "9223372036854775807",
    }
}

/// What `CREATE SEQUENCE` / `GENERATED AS IDENTITY` would use when no option is given.
fn has_default_options(s: &SequenceInfo) -> bool {
    !s.increment.starts_with('-')
        && s.start == "1"
        && s.increment == "1"
        && s.min == "1"
        && s.max == type_max(&s.data_type)
        && s.cache == "1"
        && !s.cycle
}

fn sequence_options(s: &SequenceInfo) -> String {
    format!(
        "INCREMENT BY {} MINVALUE {} MAXVALUE {} START WITH {} CACHE {} {}",
        s.increment,
        s.min,
        s.max,
        s.start,
        s.cache,
        if s.cycle { "CYCLE" } else { "NO CYCLE" }
    )
}

fn column_line(c: &ColumnInfo, seqs: &[SequenceInfo], q: &dyn Fn(&str) -> String) -> String {
    let mut line = format!("{} {}", q(&c.name), c.data_type);
    // Identity columns carry their sequence's settings, but only when they are not the defaults.
    let identity_opts = seqs
        .iter()
        .find(|s| s.identity && s.column == c.name && !has_default_options(s))
        .map(|s| format!(" ({})", sequence_options(s)))
        .unwrap_or_default();
    match (&c.identity, &c.generated, &c.default) {
        (Some(Identity::Always), _, _) => {
            line.push_str(&format!(" GENERATED ALWAYS AS IDENTITY{identity_opts}"))
        }
        (Some(Identity::ByDefault), _, _) => {
            line.push_str(&format!(" GENERATED BY DEFAULT AS IDENTITY{identity_opts}"))
        }
        (None, Some(expr), _) => line.push_str(&format!(" GENERATED ALWAYS AS ({expr}) STORED")),
        (None, None, Some(d)) => line.push_str(&format!(" DEFAULT {d}")),
        _ => {}
    }
    if c.not_null {
        line.push_str(" NOT NULL");
    }
    line
}

fn constraint_line(c: &ConstraintInfo, q: &dyn Fn(&str) -> String) -> String {
    format!("CONSTRAINT {} {}", q(&c.name), c.definition)
}

/// Indexes that are not the by-product of a PRIMARY KEY / UNIQUE / EXCLUDE constraint.
fn standalone_indexes(indexes: &[IndexInfo]) -> impl Iterator<Item = &IndexInfo> {
    indexes.iter().filter(|i| !i.backs_constraint)
}

pub(crate) fn build_ddl(d: &TableDetails, names: &DdlNames) -> String {
    let q = names.quote;
    let qualified = format!("{}.{}", q(&d.schema), q(&d.name));
    let mut out = String::new();

    match d.kind {
        RelationKind::View | RelationKind::MaterializedView => {
            let keyword = if d.kind == RelationKind::View {
                "VIEW"
            } else {
                "MATERIALIZED VIEW"
            };
            out.push_str(&format!("CREATE {keyword} {qualified} AS\n"));
            let def = d.view_definition.as_deref().unwrap_or("").trim_end();
            out.push_str(def.trim_end_matches(';'));
            out.push_str(";\n");
        }
        RelationKind::ForeignTable => {
            out.push_str(&format!(
                "-- {qualified} is a foreign table; its server and options are not reproduced here.\n"
            ));
            out.push_str(&format!("CREATE FOREIGN TABLE {qualified} (\n"));
            let lines: Vec<String> = d
                .columns
                .iter()
                .map(|c| format!("    {}", column_line(c, &d.sequences, q)))
                .collect();
            out.push_str(&lines.join(",\n"));
            out.push_str("\n) SERVER /* ... */;\n");
        }
        RelationKind::Table => {
            // Sequences a column default points at must exist before the table that uses them.
            for seq in d.sequences.iter().filter(|s| !s.identity) {
                out.push_str(&format!(
                    "CREATE SEQUENCE {}.{} AS {} {};\n",
                    q(&seq.schema),
                    q(&seq.name),
                    seq.data_type,
                    sequence_options(seq)
                ));
            }
            if d.sequences.iter().any(|s| !s.identity) {
                out.push('\n');
            }
            out.push_str(&format!("CREATE TABLE {qualified} (\n"));
            let mut lines: Vec<String> = d
                .columns
                .iter()
                .map(|c| format!("    {}", column_line(c, &d.sequences, q)))
                .collect();
            lines.extend(
                d.constraints
                    .iter()
                    .map(|c| format!("    {}", constraint_line(c, q))),
            );
            out.push_str(&lines.join(",\n"));
            out.push_str("\n)");
            if let Some(key) = &d.partition_key {
                out.push_str(&format!(" PARTITION BY {key}"));
            }
            out.push_str(";\n");
            for seq in d.sequences.iter().filter(|s| !s.identity) {
                out.push_str(&format!(
                    "ALTER SEQUENCE {}.{} OWNED BY {qualified}.{};\n",
                    q(&seq.schema),
                    q(&seq.name),
                    q(&seq.column)
                ));
            }
        }
    }

    for idx in standalone_indexes(&d.indexes) {
        out.push_str(&format!("\n{};\n", idx.definition));
    }

    for t in &d.triggers {
        out.push_str(&format!("\n{};\n", t.definition));
        let alter = match t.state {
            TriggerState::Enabled => None,
            TriggerState::Disabled => Some("DISABLE"),
            TriggerState::Replica => Some("ENABLE REPLICA"),
            TriggerState::Always => Some("ENABLE ALWAYS"),
        };
        if let Some(action) = alter {
            let object = "TABLE";
            out.push_str(&format!(
                "ALTER {object} {qualified} {action} TRIGGER {};\n",
                q(&t.name)
            ));
        }
    }

    let object = match d.kind {
        RelationKind::View => "VIEW",
        RelationKind::MaterializedView => "MATERIALIZED VIEW",
        RelationKind::ForeignTable => "FOREIGN TABLE",
        RelationKind::Table => "TABLE",
    };
    if let Some(c) = &d.comment {
        out.push_str(&format!(
            "\nCOMMENT ON {object} {qualified} IS {};\n",
            literal(c)
        ));
    }
    for col in &d.columns {
        if let Some(c) = &col.comment {
            out.push_str(&format!(
                "COMMENT ON COLUMN {qualified}.{} IS {};\n",
                q(&col.name),
                literal(c)
            ));
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog::ConstraintKind;

    fn quote(s: &str) -> String {
        if s.chars()
            .all(|c| c.is_ascii_lowercase() || c == '_' || c.is_ascii_digit())
        {
            s.to_string()
        } else {
            format!("\"{}\"", s.replace('"', "\"\""))
        }
    }

    fn col(name: &str, ty: &str) -> ColumnInfo {
        ColumnInfo {
            name: name.into(),
            quoted_name: String::new(),
            data_type: ty.into(),
            not_null: false,
            default: None,
            identity: None,
            generated: None,
            comment: None,
            is_primary_key: false,
        }
    }

    fn table() -> TableDetails {
        TableDetails {
            schema: "public".into(),
            name: "orders".into(),
            qualified_name: String::new(),
            kind: RelationKind::Table,
            columns: vec![],
            indexes: vec![],
            constraints: vec![],
            triggers: vec![],
            sequences: vec![],
            view_definition: None,
            partition_key: None,
            comment: None,
            ddl: String::new(),
        }
    }

    fn ddl(d: &TableDetails) -> String {
        build_ddl(d, &DdlNames { quote: &quote })
    }

    #[test]
    fn columns_with_defaults_identity_and_generated() {
        let mut d = table();
        let mut id = col("id", "bigint");
        id.identity = Some(Identity::Always);
        id.not_null = true;
        let mut a = col("a", "integer");
        a.identity = Some(Identity::ByDefault);
        let mut s = col("status", "text");
        s.default = Some("'new'::text".into());
        s.not_null = true;
        let mut g = col("total", "numeric");
        g.generated = Some("(price * qty)".into());
        d.columns = vec![id, a, s, g, col("Odd Name", "text")];
        assert_eq!(
            ddl(&d),
            "CREATE TABLE public.orders (\n    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,\n    \
             a integer GENERATED BY DEFAULT AS IDENTITY,\n    status text DEFAULT 'new'::text NOT NULL,\n    \
             total numeric GENERATED ALWAYS AS ((price * qty)) STORED,\n    \"Odd Name\" text\n);\n"
        );
    }

    #[test]
    fn constraints_follow_columns_and_backing_indexes_are_not_repeated() {
        let mut d = table();
        d.columns = vec![col("id", "bigint")];
        d.constraints = vec![ConstraintInfo {
            name: "orders_pkey".into(),
            kind: ConstraintKind::PrimaryKey,
            definition: "PRIMARY KEY (id)".into(),
            validated: true,
        }];
        d.indexes = vec![
            IndexInfo {
                name: "orders_pkey".into(),
                definition: "CREATE UNIQUE INDEX orders_pkey ON public.orders USING btree (id)"
                    .into(),
                unique: true,
                primary: true,
                backs_constraint: true,
            },
            IndexInfo {
                name: "orders_id_idx".into(),
                definition: "CREATE INDEX orders_id_idx ON public.orders USING btree (id)".into(),
                unique: false,
                primary: false,
                backs_constraint: false,
            },
        ];
        let text = ddl(&d);
        assert!(text.contains("    CONSTRAINT orders_pkey PRIMARY KEY (id)\n);"));
        assert_eq!(text.matches("CREATE UNIQUE INDEX").count(), 0);
        assert!(text.contains("\nCREATE INDEX orders_id_idx ON public.orders USING btree (id);\n"));
    }

    #[test]
    fn comments_are_escaped() {
        let mut d = table();
        let mut c = col("id", "int");
        c.comment = Some("it's the \"key\"".into());
        d.columns = vec![c];
        d.comment = Some("O'Brien".into());
        let text = ddl(&d);
        assert!(text.contains("COMMENT ON TABLE public.orders IS 'O''Brien';"));
        assert!(text.contains("COMMENT ON COLUMN public.orders.id IS 'it''s the \"key\"';"));
    }

    fn seq(name: &str, column: &str, identity: bool, ty: &str) -> SequenceInfo {
        SequenceInfo {
            schema: "public".into(),
            name: name.into(),
            column: column.into(),
            identity,
            data_type: ty.into(),
            start: "1".into(),
            increment: "1".into(),
            min: "1".into(),
            max: type_max(ty).into(),
            cache: "1".into(),
            cycle: false,
            last_value: None,
        }
    }

    #[test]
    fn serial_sequences_are_created_before_the_table_and_owned_by_the_column() {
        let mut d = table();
        let mut id = col("id", "integer");
        id.default = Some("nextval('orders_id_seq'::regclass)".into());
        id.not_null = true;
        d.columns = vec![id];
        d.sequences = vec![seq("orders_id_seq", "id", false, "integer")];
        let text = ddl(&d);
        let create_seq = text.find("CREATE SEQUENCE public.orders_id_seq AS integer INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1 NO CYCLE;").unwrap();
        let create_table = text.find("CREATE TABLE").unwrap();
        let owned = text
            .find("ALTER SEQUENCE public.orders_id_seq OWNED BY public.orders.id;")
            .unwrap();
        assert!(create_seq < create_table && create_table < owned, "{text}");
    }

    #[test]
    fn identity_sequences_only_show_options_that_differ_from_the_defaults() {
        let mut d = table();
        let mut plain = col("a", "integer");
        plain.identity = Some(Identity::Always);
        let mut custom = col("b", "bigint");
        custom.identity = Some(Identity::ByDefault);
        d.columns = vec![plain, custom];
        let mut s2 = seq("orders_b_seq", "b", true, "bigint");
        s2.start = "100".into();
        s2.increment = "5".into();
        s2.cache = "10".into();
        s2.cycle = true;
        d.sequences = vec![seq("orders_a_seq", "a", true, "integer"), s2];
        let text = ddl(&d);
        assert!(
            text.contains("a integer GENERATED ALWAYS AS IDENTITY,\n"),
            "{text}"
        );
        assert!(
            text.contains("b bigint GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 5 MINVALUE 1 MAXVALUE 9223372036854775807 START WITH 100 CACHE 10 CYCLE)"),
            "{text}"
        );
        // Identity sequences are part of the column: no separate statements for them.
        assert!(
            !text.contains("CREATE SEQUENCE") && !text.contains("OWNED BY"),
            "{text}"
        );
    }

    #[test]
    fn triggers_follow_indexes_and_keep_their_enabled_state() {
        use crate::catalog::TriggerInfo;
        let mut d = table();
        d.columns = vec![col("id", "int")];
        let trig = |name: &str, state| {
            TriggerInfo {
            name: name.into(),
            definition: format!("CREATE TRIGGER {name} BEFORE INSERT ON public.orders FOR EACH ROW EXECUTE FUNCTION f()"),
            timing: "BEFORE".into(),
            events: vec!["INSERT".into()],
            level: "ROW".into(),
            function: "f".into(),
            state,
        }
        };
        d.triggers = vec![
            trig("t_on", TriggerState::Enabled),
            trig("t_off", TriggerState::Disabled),
            trig("t_rep", TriggerState::Replica),
            trig("t_all", TriggerState::Always),
        ];
        let text = ddl(&d);
        assert!(text.contains("CREATE TRIGGER t_on BEFORE INSERT ON public.orders FOR EACH ROW EXECUTE FUNCTION f();\n"));
        assert!(!text.contains("ENABLE TRIGGER t_on") && !text.contains("TRIGGER t_on;"));
        assert!(text.contains("ALTER TABLE public.orders DISABLE TRIGGER t_off;"));
        assert!(text.contains("ALTER TABLE public.orders ENABLE REPLICA TRIGGER t_rep;"));
        assert!(text.contains("ALTER TABLE public.orders ENABLE ALWAYS TRIGGER t_all;"));
    }

    #[test]
    fn partitioned_table_and_views() {
        let mut d = table();
        d.columns = vec![col("id", "int")];
        d.partition_key = Some("RANGE (id)".into());
        assert!(ddl(&d).contains("\n) PARTITION BY RANGE (id);"));

        let mut v = table();
        v.kind = RelationKind::View;
        v.name = "big".into();
        v.view_definition = Some(" SELECT 1 AS x;".into());
        assert_eq!(ddl(&v), "CREATE VIEW public.big AS\n SELECT 1 AS x;\n");
        v.kind = RelationKind::MaterializedView;
        assert!(ddl(&v).starts_with("CREATE MATERIALIZED VIEW public.big AS\n"));
    }
}
