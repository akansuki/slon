<script lang="ts">
  import { app, type TreeNode } from './store.svelte';
  import ContextMenu, { type MenuItem } from './ContextMenu.svelte';
  import Icon from './Icon.svelte';
  import Self from './TreeItem.svelte';

  let { node, depth = 0 }: { node: TreeNode; depth?: number } = $props();

  const GROUP_ICON = {
    columns: 'column',
    indexes: 'index',
    constraints: 'constraint',
    triggers: 'trigger',
    sequences: 'sequence',
  } as const;

  const icon = $derived.by(() => {
    switch (node.kind) {
      case 'server':
        return 'server';
      case 'database':
        return 'database';
      case 'schema':
        return 'schema';
      case 'group':
        return node.extra.group === 'tables' ? 'table' : 'view';
      case 'detailGroup':
        return GROUP_ICON[node.extra.part ?? 'columns'];
      case 'detail':
        if (node.extra.index) return 'index';
        if (node.extra.constraint) return 'constraint';
        if (node.extra.trigger) return 'trigger';
        if (node.extra.sequence) return 'sequence';
        return node.extra.column?.isPrimaryKey ? 'key' : 'column';
      default:
        return node.extra.relation?.kind === 'view' || node.extra.relation?.kind === 'materializedView'
          ? 'view'
          : 'table';
    }
  });

  const KIND_BADGE = { primaryKey: 'PK', unique: 'UNIQUE', foreignKey: 'FK', check: 'CHECK', exclusion: 'EXCL' } as const;

  /** Small tag after the name. */
  const badge = $derived.by(() => {
    const r = node.extra.relation;
    if (node.kind === 'relation') {
      return r?.kind === 'materializedView' ? 'mat.' : r?.kind === 'foreignTable' ? 'foreign' : '';
    }
    const c = node.extra.column;
    if (c) return c.isPrimaryKey ? 'PK' : '';
    const i = node.extra.index;
    if (i) return i.primary ? 'PK' : i.unique ? 'UNIQUE' : '';
    const k = node.extra.constraint;
    if (k) return k.validated ? KIND_BADGE[k.kind] : `${KIND_BADGE[k.kind]} · not valid`;
    const t = node.extra.trigger;
    if (t) return t.state === 'enabled' ? '' : t.state;
    const q = node.extra.sequence;
    if (q) return q.identity ? 'identity' : '';
    return '';
  });

  /** Muted text after the badge: the type, or the definition. */
  const hint = $derived.by(() => {
    const c = node.extra.column;
    if (c) return c.dataType + (c.notNull ? '' : '  null');
    const i = node.extra.index;
    if (i) return i.definition.replace(/^.*? USING /, '');
    const t = node.extra.trigger;
    if (t) return `${t.timing} ${t.events.join(' OR ')} · ${t.level}`;
    const q = node.extra.sequence;
    if (q) return `${q.column} · ${q.dataType}`;
    return node.extra.constraint?.definition ?? '';
  });

  const tooltip = $derived.by(() => {
    const c = node.extra.column;
    if (c) {
      const parts = [`${c.name} ${c.dataType}`];
      if (c.identity) parts.push(c.identity === 'always' ? 'GENERATED ALWAYS AS IDENTITY' : 'GENERATED BY DEFAULT AS IDENTITY');
      if (c.generated) parts.push(`GENERATED ALWAYS AS (${c.generated}) STORED`);
      if (c.default) parts.push(`DEFAULT ${c.default}`);
      parts.push(c.notNull ? 'NOT NULL' : 'nullable');
      return parts.join(' · ') + (c.comment ? `\n${c.comment}` : '');
    }
    if (node.extra.index) return node.extra.index.definition;
    const t = node.extra.trigger;
    if (t) return `${t.definition}\n${t.state === 'enabled' ? 'Enabled' : `State: ${t.state}`} · calls ${t.function}`;
    const q = node.extra.sequence;
    if (q) {
      const bits = [
        `${q.schema}.${q.name} (${q.dataType}) for column ${q.column}`,
        q.identity ? 'identity sequence' : 'serial / owned sequence',
        q.lastValue === null ? 'not used yet' : `last value ${q.lastValue}${q.cache !== '1' ? ' (cache ' + q.cache + ': may run ahead of the rows)' : ''}`,
        `start ${q.start}, step ${q.increment}, range ${q.min} .. ${q.max}${q.cycle ? ', cycles' : ''}`,
      ];
      return bits.join('\n');
    }
    if (node.extra.constraint) return `${node.label}: ${node.extra.constraint.definition}`;
    if (node.kind === 'relation') return 'Double-click to browse the first rows, right-click for more';
    return undefined;
  });

  let menu = $state<{ x: number; y: number } | null>(null);

  const menuItems = $derived.by((): MenuItem[] => {
    const items: MenuItem[] = [];
    const k = node.kind;
    if (k === 'relation') {
      items.push(
        { label: 'Browse first 1000 rows', run: () => app.browseRelation(node) },
        { label: 'Open SELECT in new tab', run: () => void app.openSelect(node) },
        { label: 'Copy CREATE script', run: () => void app.copyDdl(node), separatorBefore: true },
        { label: 'Open CREATE script in new tab', run: () => void app.openDdl(node) },
        { label: 'Copy name', run: () => void app.copyName(node), separatorBefore: true },
        { label: 'Refresh', run: () => void app.refresh(node) },
      );
    } else if (k === 'detail') {
      const c = node.extra.column;
      items.push({
        label: 'Copy name',
        run: () => void app.copyName(node, c ? c.quotedName : node.label),
      });
      const definition =
        node.extra.index?.definition ?? node.extra.constraint?.definition ?? node.extra.trigger?.definition;
      if (definition) {
        items.push({ label: 'Copy definition', run: () => void app.copyName(node, definition) });
      }
    } else if (k === 'database' || k === 'schema') {
      items.push({ label: 'Copy name', run: () => void app.copyName(node) });
    }
    return items;
  });

  function onContextMenu(e: MouseEvent) {
    if (menuItems.length === 0) return;
    e.preventDefault();
    app.selected = node;
    menu = { x: e.clientX, y: e.clientY };
  }

  function activate() {
    app.selected = node;
    // A table's row opens it on double-click, so only its chevron expands it.
    if (node.expandable && node.kind !== 'relation') void app.toggle(node);
  }

  function onkeydown(e: KeyboardEvent) {
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault();
      if (node.kind === 'relation') app.browseRelation(node);
      else activate();
    } else if (e.key === 'ContextMenu' || (e.shiftKey && e.key === 'F10')) {
      e.preventDefault();
      const r = (e.currentTarget as HTMLElement).getBoundingClientRect();
      if (menuItems.length) menu = { x: r.left + 24, y: r.bottom };
    } else if (e.key === 'ArrowRight' && node.expandable && !node.expanded) {
      void app.expand(node);
    } else if (e.key === 'ArrowLeft' && node.expanded) {
      app.collapse(node);
    }
  }
</script>

<div
  class="row"
  class:selected={app.selected === node}
  style:padding-left="{8 + depth * 14}px"
  role="treeitem"
  aria-selected={app.selected === node}
  aria-expanded={node.expandable ? node.expanded : undefined}
  tabindex="0"
  onclick={activate}
  ondblclick={() => node.kind === 'relation' && app.browseRelation(node)}
  oncontextmenu={onContextMenu}
  {onkeydown}
  title={tooltip}
>
  <!-- svelte-ignore a11y_click_events_have_key_events, a11y_no_static_element_interactions -->
  <span
    class="chev"
    class:open={node.expanded}
    class:hidden={!node.expandable}
    onclick={(e) => {
      if (node.kind === 'relation') {
        e.stopPropagation();
        app.selected = node;
        void app.toggle(node);
      }
    }}
  >
    <Icon name="chevron" size={12} />
  </span>
  <Icon name={icon} size={15} />
  <span class="label">{node.label}</span>
  {#if badge}<span class="badge">{badge}</span>{/if}
  {#if hint}<span class="hint">{hint}</span>{/if}
  {#if node.loading}<span class="spinner"></span>{/if}
  {#if node.kind === 'server'}
    <button
      class="ghost refresh"
      title="Refresh"
      onclick={(e) => {
        e.stopPropagation();
        void app.refresh(node);
      }}
    >
      <Icon name="refresh" size={13} />
    </button>
  {/if}
</div>

{#if menu}
  <ContextMenu x={menu.x} y={menu.y} items={menuItems} onclose={() => (menu = null)} />
{/if}

{#if node.error}
  <div class="error" style:padding-left="{30 + depth * 14}px" role="alert">{node.error}</div>
{/if}

{#if node.expanded && node.children}
  {#each node.children as child (child.id)}
    <Self node={child} depth={depth + 1} />
  {/each}
  {#if node.children.length === 0}
    <div class="empty" style:padding-left="{30 + depth * 14}px">(empty)</div>
  {/if}
{/if}

